-- #218: 공식 이미지를 내리고 되돌리는 함수와 이력. 절차는 docs/image-takedown.md, 결정은 ADR 0006.

-- ─────────────────────────────────────────────
-- 1. image_takedown_requests: 내리기 호출 한 번. 바뀐 행이 없어도 남는다
--    요청자 개인정보는 넣지 않는다. note 에는 메일 제목처럼 찾아갈 단서만 적는다.
-- ─────────────────────────────────────────────
create table "public"."image_takedown_requests" (
  "batch_id"    uuid   primary key,
  "scope"       text   not null check (scope in ('gacha', 'anime', 'all')),
  "target_ids"  bigint[],
  "reason"      text   not null check (reason in ('rights_holder', 'store_review', 'other')),
  "note"        text   not null check (btrim(note) <> ''),
  "created_at"  timestamptz not null default now(),
  "restored_at" timestamptz
);

-- ─────────────────────────────────────────────
-- 2. image_takedowns: 요청이 덮은 행. 겹침을 알아야 하므로 이미 비어 있던 행도 남긴다
--    row_id 는 gacha · gacha_items 어느 쪽이든 가리키고 재시드로 사라질 수 있어 FK 를 걸지 않는다.
--    restored_at 은 그 행 처리가 끝났을 때만 찍는다. 다른 요청에 걸려 건너뛴 행과 못 찾은 행은 null 이다.
-- ─────────────────────────────────────────────
create table "public"."image_takedowns" (
  "id"                  bigint generated by default as identity primary key,
  "batch_id"            uuid   not null references "public"."image_takedown_requests"(batch_id),
  "source_table"        text   not null check (source_table in ('gacha', 'gacha_items')),
  "row_id"              bigint not null,
  "gacha_id"            bigint not null,
  "previous_image_link" text,
  "restored_at"         timestamptz
);
create index "image_takedowns_batch_id_idx" on "public"."image_takedowns"(batch_id);
create index "image_takedowns_source_row_idx" on "public"."image_takedowns"(source_table, row_id);

-- 정책 없음 + 권한 회수: 앱은 읽지도 쓰지도 못한다. 운영자는 SQL Editor 로 다룬다.
alter table "public"."image_takedown_requests" enable row level security;
alter table "public"."image_takedowns" enable row level security;
revoke all on table "public"."image_takedown_requests" from "anon", "authenticated";
revoke all on table "public"."image_takedowns" from "anon", "authenticated";
revoke all on sequence "public"."image_takedowns_id_seq" from "anon", "authenticated";

-- ─────────────────────────────────────────────
-- 3. take_down_images: 범위 안의 이미지 URL 을 이력에 남기고 비운다
--    앱은 gacha.image_link 를 보여 주므로 gacha_items 와 함께 비워야 화면에서 사라진다.
--    p_scope: 'gacha'(p_ids = 가챠 id 들), 'anime'(p_ids = 미디어 id 들), 'all'(p_ids = null)
-- ─────────────────────────────────────────────
create function "public"."take_down_images"(
  p_scope text,
  p_ids bigint[],
  p_reason text,
  p_note text
)
returns table (takedown_batch uuid, target_gachas bigint, gacha_rows bigint, item_rows bigint)
language plpgsql
set search_path = ''
as $$
declare
  v_batch uuid := gen_random_uuid();
  v_gacha_ids bigint[];
  v_missing bigint[];
  v_gacha_rows bigint;
  v_item_rows bigint;
begin
  if p_scope is null or p_scope not in ('gacha', 'anime', 'all') then
    raise exception 'p_scope 는 gacha, anime, all 중 하나여야 한다';
  end if;
  -- 'all' 이 id 를 무시하면 일부만 내리려던 호출이 전체를 지운다
  if (p_scope = 'all') <> (p_ids is null) then
    raise exception 'gacha · anime 는 p_ids 가 필요하고, all 은 p_ids 가 null 이어야 한다';
  end if;
  if p_scope <> 'all' and (cardinality(p_ids) = 0 or array_position(p_ids, null::bigint) is not null) then
    raise exception 'p_ids 는 비어 있거나 null 을 포함할 수 없다';
  end if;

  -- 틀린 id 가 "이미 내림" 과 구분되지 않으면 내리지 못한 채 회신하게 된다
  v_missing := array(
    select x from unnest(p_ids) x
    where (p_scope = 'gacha' and not exists (select 1 from public.gacha g where g.id = x))
       or (p_scope = 'anime' and not exists (select 1 from public.anime a where a.id = x))
  );
  if cardinality(v_missing) > 0 then
    raise exception '없는 id: %', v_missing;
  end if;

  insert into public.image_takedown_requests (batch_id, scope, target_ids, reason, note)
  values (v_batch, p_scope, p_ids, p_reason, p_note);

  v_gacha_ids := array(
    select g.id from public.gacha g
    where p_scope = 'all'
       or (p_scope = 'gacha' and g.id = any(p_ids))
       or (p_scope = 'anime' and g.anime_id = any(p_ids))
  );

  -- 이력과 비우기를 한 문장으로 묶어, 그 사이에 바뀐 URL 이 이력 없이 지워지지 않게 한다
  with targets as (
    select g.id, g.image_link from public.gacha g
    where g.id = any(v_gacha_ids)
    for update
  ), recorded as (
    insert into public.image_takedowns (batch_id, source_table, row_id, gacha_id, previous_image_link)
    select v_batch, 'gacha', t.id, t.id, t.image_link from targets t
  ), cleared as (
    update public.gacha g set image_link = null
    from targets t
    where g.id = t.id and t.image_link is not null
    returning 1
  )
  select count(*) into v_gacha_rows from cleared;

  with targets as (
    select i.id, i.gacha_id, i.image_link from public.gacha_items i
    where i.gacha_id = any(v_gacha_ids)
    for update
  ), recorded as (
    insert into public.image_takedowns (batch_id, source_table, row_id, gacha_id, previous_image_link)
    select v_batch, 'gacha_items', t.id, t.gacha_id, t.image_link from targets t
  ), cleared as (
    update public.gacha_items i set image_link = null
    from targets t
    where i.id = t.id and t.image_link is not null
    returning 1
  )
  select count(*) into v_item_rows from cleared;

  return query select v_batch, cardinality(v_gacha_ids)::bigint, v_gacha_rows, v_item_rows;
end;
$$;

-- ─────────────────────────────────────────────
-- 4. restore_images: 요청 하나를 취소한다. 행은 그 행을 덮는 유효한 요청이 모두 풀릴 때 돌아온다
--    반환: 되살린 수(gacha_rows, item_rows), 다른 요청에 걸려 건너뛴 수, 재시드 등으로 못 찾은 수
-- ─────────────────────────────────────────────
create function "public"."restore_images"(p_batch uuid)
returns table (gacha_rows bigint, item_rows bigint, skipped_rows bigint, missing_rows bigint)
language plpgsql
set search_path = ''
as $$
declare
  v_row record;
  v_url text;
  v_exists boolean;
  v_updated bigint;
  v_gacha_rows bigint := 0;
  v_item_rows bigint := 0;
  v_skipped bigint := 0;
  v_missing bigint := 0;
begin
  update public.image_takedown_requests r set restored_at = now()
  where r.batch_id = p_batch and r.restored_at is null;
  if not found then
    raise exception '없거나 이미 되돌린 요청: %', p_batch;
  end if;

  for v_row in
    select t.source_table, t.row_id from public.image_takedowns t
    where t.batch_id = p_batch and t.restored_at is null
  loop
    if exists (
      select 1 from public.image_takedowns o
      join public.image_takedown_requests r on r.batch_id = o.batch_id
      where r.restored_at is null and o.source_table = v_row.source_table and o.row_id = v_row.row_id
    ) then
      v_skipped := v_skipped + 1;
      continue;
    end if;

    -- 먼저 풀린 요청이 건너뛴 행의 URL 도 후보다 (이 요청은 이미 비어 있던 행만 덮었을 수 있다)
    select o.previous_image_link into v_url
    from public.image_takedowns o
    where o.source_table = v_row.source_table and o.row_id = v_row.row_id
      and o.restored_at is null and o.previous_image_link is not null
    order by o.id desc
    limit 1;

    -- 내린 뒤 새로 넣은 URL 은 덮어쓰지 않는다
    if v_row.source_table = 'gacha' then
      v_exists := exists (select 1 from public.gacha g where g.id = v_row.row_id);
      update public.gacha g set image_link = v_url
      where g.id = v_row.row_id and g.image_link is null and v_url is not null;
      get diagnostics v_updated = row_count;
      v_gacha_rows := v_gacha_rows + v_updated;
    else
      v_exists := exists (select 1 from public.gacha_items i where i.id = v_row.row_id);
      update public.gacha_items i set image_link = v_url
      where i.id = v_row.row_id and i.image_link is null and v_url is not null;
      get diagnostics v_updated = row_count;
      v_item_rows := v_item_rows + v_updated;
    end if;

    if not v_exists then
      v_missing := v_missing + 1;
      continue;
    end if;

    update public.image_takedowns o set restored_at = now()
    where o.source_table = v_row.source_table and o.row_id = v_row.row_id and o.restored_at is null;
  end loop;

  return query select v_gacha_rows, v_item_rows, v_skipped, v_missing;
end;
$$;

-- 새 함수는 기본으로 anon 도 실행할 수 있어 회수한다 (없으면 RPC 로 노출된다)
revoke all on function "public"."take_down_images"(text, bigint[], text, text)
  from public, "anon", "authenticated";
revoke all on function "public"."restore_images"(uuid)
  from public, "anon", "authenticated";
