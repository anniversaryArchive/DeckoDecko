-- 20261022003611_catalog_tables.sql
-- #114/#115: 카탈로그 보강 + 신규 테이블.
-- 기획서 7절(미디어/가챠/아이템) · 12절 기준. 테이블명은 레거시 그대로 anime 를 쓴다.
-- 레거시 테이블의 쓰기 잠금 · 읽기 정책은 #133 의 20261019105308_lock_down_legacy_writes 가 이미 했다.
-- 정책 이름은 그 파일 규칙(<테이블>_select_<대상>)을 따른다.

-- ─────────────────────────────────────────────
-- 1. anime
--    - 별칭(검색용) 추가 — 기획서 7절 aliases. 복수 별칭을 담으려고 text[].
--    - created_at · updated_at 을 다른 테이블처럼 timestamptz 로 맞춘다.
--      기존 값은 Supabase 기본 시간대(UTC)로 저장된 것으로 보고 변환한다.
--    - 105308 이 남긴 anime_id_seq 의 SELECT 권한까지 회수한다.
-- ─────────────────────────────────────────────
alter table "public"."anime"
  add column if not exists "aliases" text[] not null default '{}';

alter table "public"."anime"
  alter column "created_at" type timestamptz using "created_at" at time zone 'UTC',
  alter column "updated_at" type timestamptz using "updated_at" at time zone 'UTC';

revoke all on sequence "public"."anime_id_seq" from "anon", "authenticated";

-- ─────────────────────────────────────────────
-- 2. gacha
--    - 레거시의 updated_at 이 text 라 timestamptz 로 바로잡는다.
--      빈 문자열 · 공백만 있는 값은 null 로 둔다.
--      dev 값의 형식 · 시간대는 push 전에 확인한다 (#135 리뷰).
--    - id 에 자동 번호(identity)를 켜고, 지금 있는 값 다음부터 나오게 맞춘다.
--    - anime_id FK 에 인덱스를 단다 (작품별 가챠 목록).
--    - 발매 월(release_month): 그 달 1일로 저장한다. 앱은 "YYYY-MM" 으로 바꿔 쓴다.
--    - 수정 시 updated_at 갱신은 파일 끝의 set_updated_at 트리거가 한다.
-- ─────────────────────────────────────────────
alter table "public"."gacha"
  alter column "updated_at" type timestamptz using nullif(btrim("updated_at"), '')::timestamptz;

alter table "public"."gacha"
  alter column "created_at" set default now(),
  alter column "updated_at" set default now();

alter table "public"."gacha"
  alter column "id" add generated by default as identity;

select setval(
  pg_get_serial_sequence('public.gacha', 'id'),
  coalesce((select max(id) from "public"."gacha"), 0) + 1,
  false
);

revoke all on sequence "public"."gacha_id_seq" from "anon", "authenticated";

create index "gacha_anime_id_idx" on "public"."gacha"(anime_id);

alter table "public"."gacha"
  add column "release_month" date
  constraint "gacha_release_month_first_day"
    check (extract(day from release_month) = 1);

-- ─────────────────────────────────────────────
-- 3. gacha_items: 가챠 1개가 여러 아이템(라인업)을 가진다
-- ─────────────────────────────────────────────
create table "public"."gacha_items" (
  "id"         bigint generated by default as identity primary key,
  "gacha_id"   bigint not null references "public"."gacha"(id) on delete cascade,
  "name"       text   not null,
  "name_kr"    text,
  "image_link" text,
  "sort_order" int    not null default 0,
  "created_at" timestamptz not null default now(),
  "updated_at" timestamptz not null default now()
);
create index "gacha_items_gacha_id_idx" on "public"."gacha_items"(gacha_id);

alter table "public"."gacha_items" enable row level security;
create policy "gacha_items_select_all" on "public"."gacha_items"
  for select to "anon", "authenticated" using (true);

-- ─────────────────────────────────────────────
-- 4. notice: 공지
--    기본값은 비공개. 공개하려면 백오피스에서 is_published 를 켠다.
-- ─────────────────────────────────────────────
create table "public"."notice" (
  "id"           bigint generated by default as identity primary key,
  "title"        text not null,
  "body"         text not null,
  "is_published" boolean not null default false,
  "created_at"   timestamptz not null default now(),
  "updated_at"   timestamptz not null default now()
);

alter table "public"."notice" enable row level security;
-- 게시된 공지만 공개
create policy "notice_select_published" on "public"."notice"
  for select to "anon", "authenticated" using (is_published = true);

-- ─────────────────────────────────────────────
-- 5. gacha_view_log: 가챠 조회 로그 (기기당·가챠당 하루 1건)
--    anon 은 직접 쓰지 못하고, log_gacha_view 함수로만 기록한다.
--    device_id 는 앱이 만드는 익명 설치 식별자(UUID). 타입으로 형식을 강제한다.
-- ─────────────────────────────────────────────
create table "public"."gacha_view_log" (
  "id"         bigint generated by default as identity primary key,
  "gacha_id"   bigint not null references "public"."gacha"(id) on delete cascade,
  "device_id"  uuid   not null,
  "viewed_on"  date   not null default (now() at time zone 'Asia/Seoul'),
  "created_at" timestamptz not null default now()
);

-- 기기·가챠·날짜 조합은 하루 1건 (중복 조회 방지).
-- 첫 컬럼이 gacha_id 라 가챠별 조회에도 이 인덱스를 쓴다.
create unique index "gacha_view_log_unique_daily"
  on "public"."gacha_view_log"(gacha_id, device_id, viewed_on);
-- 기간별 인기 집계용
create index "gacha_view_log_viewed_on_gacha_id_idx"
  on "public"."gacha_view_log"(viewed_on, gacha_id);

alter table "public"."gacha_view_log" enable row level security;

-- ─────────────────────────────────────────────
-- 6. 새 테이블 권한
--    Supabase 는 public 에 새로 만든 테이블 · 시퀀스에 anon/authenticated 의
--    모든 권한을 자동으로 준다(default privileges). TRUNCATE 는 RLS 를 거치지 않으므로
--    전부 회수한 뒤 필요한 SELECT 만 다시 준다.
-- ─────────────────────────────────────────────
revoke all on table "public"."gacha_items", "public"."notice", "public"."gacha_view_log"
  from "anon", "authenticated";
grant select on table "public"."gacha_items", "public"."notice" to "anon", "authenticated";

revoke all on sequence "public"."gacha_items_id_seq", "public"."notice_id_seq",
                       "public"."gacha_view_log_id_seq"
  from "anon", "authenticated";

-- ─────────────────────────────────────────────
-- 7. updated_at 자동 갱신 트리거
--    행을 UPDATE 하면 updated_at 을 지금 시각으로 바꾼다.
-- ─────────────────────────────────────────────
create or replace function "public"."set_updated_at"()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- 트리거 전용 함수라 API 로 직접 부를 수 없게 막는다
revoke all on function "public"."set_updated_at"() from public, "anon", "authenticated";

create trigger "anime_set_updated_at"
  before update on "public"."anime"
  for each row execute function "public"."set_updated_at"();

create trigger "gacha_set_updated_at"
  before update on "public"."gacha"
  for each row execute function "public"."set_updated_at"();

create trigger "gacha_items_set_updated_at"
  before update on "public"."gacha_items"
  for each row execute function "public"."set_updated_at"();

create trigger "notice_set_updated_at"
  before update on "public"."notice"
  for each row execute function "public"."set_updated_at"();
