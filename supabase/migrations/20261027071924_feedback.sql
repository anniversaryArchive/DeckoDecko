-- 20261027071924_feedback.sql
-- 요청 · 문의(feedback). 앱이 보낸 가챠 등록 요청 · 버그 신고 · 제안을 받는다. 기획서 4-2 · 7절.
--
-- - 로그인이 없어 기기 UUID(device_uuid)로 사람을 구분한다.
-- - anon 은 테이블에 직접 쓰지도 읽지도 못한다. 보내기는 submit_feedback, 내 문의는 list_my_feedback 로만.
--   직접 insert 를 열면 하루 건수 제한을 건너뛸 수 있어서 쓰기도 함수로만 받는다.
-- - 상태 · 답변 · 내부 메모는 service role(백오피스 · 대시보드)만 바꾼다.
-- - 한계: 기기 UUID 를 아는 사람은 그 기기의 문의를 볼 수 있고, UUID 를 바꾸면 하루 제한을 다시 받는다. 익명 설계라 완전히 막지 않는다.

-- ─────────────────────────────────────────────
-- 1. 테이블
--    media_id 는 기획서의 media, 지금 테이블 이름은 anime 다.
--    status: received(접수) -> checking(확인 중) -> done(반영됨) / hold(보류)
-- ─────────────────────────────────────────────
create table "public"."feedback" (
  "id"             bigint generated by default as identity primary key,
  "kind"           text   not null check (kind in ('request', 'bug', 'idea')),
  "title"          text   check (char_length(title) <= 100),
  "body"           text   check (char_length(body) <= 2000),
  "media_id"       bigint references "public"."anime"(id) on delete set null,
  "media_name_raw" text   check (char_length(media_name_raw) <= 100),
  "photo_url"      text   check (char_length(photo_url) <= 500),
  "device_uuid"    uuid   not null,
  "app_version"    text   check (char_length(app_version) <= 32),
  "status"         text   not null default 'received'
                          check (status in ('received', 'checking', 'done', 'hold')),
  "admin_reply"    text   check (char_length(admin_reply) <= 300),
  "admin_note"     text,
  "created_at"     timestamptz not null default now(),
  "updated_at"     timestamptz not null default now(),
  -- 가챠 등록 요청은 가챠 이름(title)이, 버그 · 제안은 내용(body)이 꼭 있어야 한다
  constraint "feedback_request_has_title" check (kind <> 'request' or title is not null),
  constraint "feedback_other_has_body" check (kind = 'request' or body is not null)
);

-- 기기별 하루 건수 세기 · 내 문의 목록
create index "feedback_device_uuid_created_at_idx"
  on "public"."feedback"(device_uuid, created_at desc);

-- 작품을 지울 때(on delete set null) feedback 을 다 훑지 않게
create index "feedback_media_id_idx"
  on "public"."feedback"(media_id);

alter table "public"."feedback" enable row level security;

-- 정책 없음 + 권한 회수: anon · authenticated 는 아래 함수로만 다룬다
revoke all on table "public"."feedback" from "anon", "authenticated";
revoke all on sequence "public"."feedback_id_seq" from "anon", "authenticated";

create trigger "feedback_set_updated_at"
  before update on "public"."feedback"
  for each row execute function "public"."set_updated_at"();

-- ─────────────────────────────────────────────
-- 2. 보내기: submit_feedback
--    기기당 하루(한국 날짜) 5건까지. 넘으면 PT429 로 던져 API 가 HTTP 429 를 돌려준다.
--    같은 기기가 동시에 여러 번 보내도 세는 사이에 끼지 않게 기기별 잠금을 건다.
--    앞뒤 공백은 지우고, 빈 글자는 null 로 본다. 길이 · 필수 검사는 테이블 제약이 한다.
-- ─────────────────────────────────────────────
create or replace function "public"."submit_feedback"(
  p_device_uuid    uuid,
  p_kind           text,
  p_title          text   default null,
  p_body           text   default null,
  p_media_id       bigint default null,
  p_media_name_raw text   default null,
  p_photo_url      text   default null,
  p_app_version    text   default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  daily_limit constant int := 5;
  today_start timestamptz := ((now() at time zone 'Asia/Seoul')::date)::timestamp at time zone 'Asia/Seoul';
  new_id bigint;
begin
  if p_device_uuid is null then
    raise exception 'device_uuid is required' using errcode = '22004';
  end if;

  -- 잠금 키는 DB 전체가 같이 쓰므로, 다른 잠금과 겹치지 않게 'feedback:' 을 앞에 붙인다
  perform pg_advisory_xact_lock(hashtextextended('feedback:' || p_device_uuid::text, 0));

  if (select count(*) from public.feedback f
      where f.device_uuid = p_device_uuid and f.created_at >= today_start) >= daily_limit then
    raise exception 'feedback daily limit (%) reached', daily_limit using errcode = 'PT429';
  end if;

  insert into public.feedback
    (kind, title, body, media_id, media_name_raw, photo_url, device_uuid, app_version)
  values (
    p_kind,
    nullif(btrim(p_title), ''),
    nullif(btrim(p_body), ''),
    -- 없는 작품 id 는 FK 에러 대신 비운다 (적은 글자는 media_name_raw 에 남는다)
    (select a.id from public.anime a where a.id = p_media_id),
    nullif(btrim(p_media_name_raw), ''),
    nullif(btrim(p_photo_url), ''),
    p_device_uuid,
    nullif(btrim(p_app_version), '')
  )
  returning id into new_id;

  return new_id;
end;
$$;

revoke all on function "public"."submit_feedback"(uuid, text, text, text, bigint, text, text, text) from public;
grant execute on function "public"."submit_feedback"(uuid, text, text, text, bigint, text, text, text)
  to "anon", "authenticated";

-- ─────────────────────────────────────────────
-- 3. 내 문의: list_my_feedback
--    그 기기 UUID 의 문의만, 최신순. admin_note(내부 메모)와 device_uuid 는 돌려주지 않는다.
--    limit · offset 은 검색 RPC 와 같은 규칙: limit 은 1 미만 · null 이면 기본 20, 상한 50. offset 은 0 미만 · null 이면 0.
-- ─────────────────────────────────────────────
create or replace function "public"."list_my_feedback"(
  p_device_uuid uuid,
  p_limit       int default 20,
  p_offset      int default 0
)
returns table (
  id             bigint,
  kind           text,
  title          text,
  body           text,
  media_id       bigint,
  media_name_raw text,
  photo_url      text,
  status         text,
  admin_reply    text,
  created_at     timestamptz,
  updated_at     timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select f.id, f.kind, f.title, f.body, f.media_id, f.media_name_raw, f.photo_url,
         f.status, f.admin_reply, f.created_at, f.updated_at
  from public.feedback f
  where f.device_uuid = p_device_uuid
  order by f.created_at desc, f.id desc
  limit case when p_limit >= 1 then least(p_limit, 50) else 20 end
  offset case when p_offset >= 0 then p_offset else 0 end
$$;

revoke all on function "public"."list_my_feedback"(uuid, int, int) from public;
grant execute on function "public"."list_my_feedback"(uuid, int, int) to "anon", "authenticated";
